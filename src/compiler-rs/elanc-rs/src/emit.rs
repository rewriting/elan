    // Decision trees and rules
    // ------------------------------------------------------------------

    fn decision(&mut self, d: &Decision, rules: &[RuleIr]) {
        match d {
            Decision::Fail => {}
            Decision::Try {
                rule,
                bindings,
                next,
            } => {
                self.try_rule(*rule, bindings, rules);
                self.decision(next, rules);
            }
            Decision::Switch {
                occ,
                sort,
                cases,
                default,
            } => match &self.ir.sorts[*sort].repr {
                Repr::Enum { .. } => self.enum_switch(occ, *sort, cases, default, rules),
                Repr::Family(_) => self.family_switch(occ, *sort, cases, default, rules),
            },
        }
    }

    fn enum_switch(
        &mut self,
        occ: &Occ,
        sort: SortId,
        cases: &[(Head, Decision)],
        default: &Option<Box<Decision>>,
        rules: &[RuleIr],
    ) {
        let ir = self.ir;
        let en = &ir.sorts[sort].type_name;
        let name = occ_name(occ);
        self.out.open(&format!("match &**{name} {{"));
        for (h, d) in cases {
            let Head::Op(o) = h else {
                unreachable!("literal in an enum sort")
            };
            let op = &ir.ops[*o];
            let vn = op.variant.as_ref().expect("case without variant");
            let fields: Vec<String> = (0..op.args.len())
                .map(|i| {
                    let mut c = occ.clone();
                    c.push(i);
                    occ_name(&c)
                })
                .collect();
            if fields.is_empty() {
                self.out.open(&format!("{en}::{vn} => {{"));
            } else {
                self.out
                    .open(&format!("{en}::{vn}({}) => {{", fields.join(", ")));
            }
            self.decision(d, rules);
            self.out.close("}");
        }
        match default.as_deref() {
            None => {}
            Some(Decision::Fail) => self.out.line("_ => {}"),
            Some(d) => {
                self.out.open("_ => {");
                self.decision(d, rules);
                self.out.close("}");
            }
        }
        self.out.close("}");
    }

    fn family_switch(
        &mut self,
        occ: &Occ,
        sort: SortId,
        cases: &[(Head, Decision)],
        default: &Option<Box<Decision>>,
        rules: &[RuleIr],
    ) {
        let ir = self.ir;
        let name = occ_name(occ);
        let label = format!("'s{}", self.next());
        self.out.open(&format!("{label}: {{"));
        for (h, d) in cases {
            let mut closes = 1;
            match h {
                Head::Int(_) | Head::Str(_) | Head::Ident(_) => {
                    let t = self.lit_test(sort, &name, h);
                    self.out.open(&format!("if {t} {{"));
                }
                Head::Op(o) => {
                    let op = &ir.ops[*o];
                    match op.kind {
                        OpKind::BoolConst(_) => {
                            let t = self.lit_test(sort, &name, h);
                            self.out.open(&format!("if {t} {{"));
                        }
                        OpKind::Injection => {
                            if self.wrapped(sort) {
                                let t = self.inj_test(op.args[0], &name);
                                self.out.open(&format!("if {t} {{"));
                            } else {
                                self.out.open("{");
                            }
                            let mut c = occ.clone();
                            c.push(0);
                            self.out.line(&format!("let {} = {name};", occ_name(&c)));
                        }
                        _ => {
                            // a stuck term of the family
                            let (en, _) = self.variant_enum(*o);
                            let vn = op.variant.as_ref().expect("case without variant");
                            let s = format!("s{}", self.next());
                            self.out
                                .open(&format!("if let Builtin::Stuck({s}) = {name} {{"));
                            let fields: Vec<String> = (0..op.args.len())
                                .map(|i| {
                                    let mut c = occ.clone();
                                    c.push(i);
                                    occ_name(&c)
                                })
                                .collect();
                            let pat = if fields.is_empty() {
                                format!("{en}::{vn}")
                            } else {
                                format!("{en}::{vn}({})", fields.join(", "))
                            };
                            self.out.open(&format!("if let {pat} = &**{s} {{"));
                            closes = 2;
                        }
                    }
                }
            }
            self.decision(d, rules);
            self.out.line(&format!("break {label};"));
            for _ in 0..closes {
                self.out.close("}");
            }
        }
        if let Some(d) = default {
            self.decision(d, rules);
        }
        self.out.close("}");
    }

    fn try_rule(&mut self, r: RuleId, bindings: &[(VarId, Occ)], rules: &[RuleIr]) {
        let rule = &rules[r];
        let label = format!("'r{}", self.next());
        self.out.line(&format!("// {}", rule.text));
        if self.label_mode {
            self.out.line("let mut found = false;");
        }
        self.out.open(&format!("{label}: {{"));
        for (v, occ) in bindings {
            self.out
                .line(&format!("let {} = {};", rule.vars[*v].name, occ_name(occ)));
        }
        self.conds(rule, 0, &format!("break {label};"), 0);
        self.out.close("}");
        if self.label_mode {
            self.out.line("if first && found { return false; }");
        }
    }

    /// The conditions of `rule` from the i-th, then its application. `fail`
    /// is the statement that abandons this attempt (`break 'r` in the
    /// rule's block, `return false` in the continuation of a strategy, which
    /// then gives its next result); `depth` is the number of enclosing
    /// continuations.
    fn conds(&mut self, rule: &RuleIr, i: usize, fail: &str, depth: usize) {
        for (j, c) in rule.conds.iter().enumerate().skip(i) {
            match c {
                Cond::Same(a, b) => {
                    self.out.line(&format!(
                        "if {} != {} {{ {fail} }}",
                        rule.vars[*a].name, rule.vars[*b].name
                    ));
                }
                Cond::If(e) => {
                    let ex = self.expr(e, &rule.vars);
                    let bool_sort = self.expr_sort(e, &rule.vars);
                    let t = if self.wrapped(bool_sort) {
                        format!(
                            "!matches!({{ let c: {} = {ex}; c }}, Builtin::Val(true))",
                            self.ty(bool_sort)
                        )
                    } else {
                        format!("!{ex}")
                    };
                    self.out.line(&format!("if {t} {{ {fail} }}"));
                }
                Cond::Let(v, e) => {
                    let ex = self.expr(e, &rule.vars);
                    self.out
                        .line(&format!("let {} = &{ex};", rule.vars[*v].name));
                }
                Cond::Match(p, e) => {
                    let ex = self.expr(e, &rule.vars);
                    let s = self.expr_sort(e, &rule.vars);
                    let m = format!("m{}", self.next());
                    self.out.line(&format!("let {m} = &{ex};"));
                    self.pattern_check(p, &m, s, fail, &rule.vars);
                }
                Cond::Apply {
                    pattern,
                    strategy,
                    expr,
                } => {
                    let st = &self.ir.strategies[*strategy];
                    let ex = self.expr(expr, &rule.vars);
                    let m = format!("m{}", self.next());
                    let y = format!("y{}", self.next());
                    let ty = self.ty(st.sort);
                    self.out.line(&format!("let {m} = &{ex};"));
                    self.out.line(&format!(
                        "// each result of {} (the conditions after it backtrack)",
                        st.name
                    ));
                    let call = format!("{}({m}, &mut |{y}: &{ty}| -> bool {{", st.fun);
                    // a normalisation function keeps the first result
                    let keep_first = !self.label_mode && depth == 0;
                    if keep_first {
                        self.out.line("let mut res = None;");
                        self.out.open(&call);
                    } else {
                        self.out.open(&format!("if {call}"));
                    }
                    self.pattern_check(pattern, &y, st.sort, "return false;", &rule.vars);
                    self.conds(rule, j + 1, "return false;", depth + 1);
                    self.out.line("false");
                    if keep_first {
                        self.out.close("});");
                        self.out.line("if let Some(r) = res { return r; }");
                    } else {
                        self.out.close("}) { return true; }");
                    }
                    return;
                }
            }
        }
        self.out.line("step();");
        let rhs = self.expr(&rule.rhs, &rule.vars);
        if self.label_mode {
            self.out.line("found = true;");
            self.out.line(&format!("if k(&{rhs}) {{ return true; }}"));
        } else if depth == 0 {
            self.out.line(&format!("return {rhs};"));
        } else {
            self.out.line(&format!("res = Some({rhs});"));
            self.out.line("return true;");
        }
    }

    fn expr_sort(&self, e: &Expr, vars: &[VarIr]) -> SortId {
        match e {
            Expr::Var(v) => vars[*v].sort,
            Expr::Op { op, .. } => self.ir.ops[*op].result,
            Expr::Int(_) => self.int_sort().unwrap(),
            Expr::Str(_) => self.str_sort().unwrap(),
            Expr::Ident(_) => self.ident_sort().unwrap(),
        }
    }

    /// Match the value at `scrut` (a reference of sort `s`) against `p`,
    /// binding its variables; run `fail` when it does not match.
    fn pattern_check(&mut self, p: &Pattern, scrut: &str, s: SortId, fail: &str, vars: &[VarIr]) {
        let ir = self.ir;
        match p {
            Pattern::Var(v) => self.out.line(&format!("let {} = {scrut};", vars[*v].name)),
            Pattern::Int(_) | Pattern::Str(_) | Pattern::Ident(_) => {
                let h = match p {
                    Pattern::Int(n) => Head::Int(*n),
                    Pattern::Str(x) => Head::Str(x.clone()),
                    Pattern::Ident(i) => Head::Ident(*i),
                    _ => unreachable!(),
                };
                let t = self.lit_test(s, scrut, &h);
                self.out.line(&format!("if !({t}) {{ {fail} }}"));
            }
            Pattern::Op { op, args } => {
                let o = &ir.ops[*op];
                match o.kind {
                    OpKind::BoolConst(_) => {
                        let t = self.lit_test(s, scrut, &Head::Op(*op));
                        self.out.line(&format!("if !({t}) {{ {fail} }}"));
                    }
                    OpKind::Injection => {
                        if self.wrapped(s) {
                            let t = self.inj_test(o.args[0], scrut);
                            self.out.line(&format!("if !({t}) {{ {fail} }}"));
                        }
                        self.pattern_check(&args[0], scrut, o.args[0], fail, vars);
                    }
                    _ if o.variant.is_none() => {
                        self.out
                            .line(&format!("{fail} // {} is never a normal form", o.decl));
                    }
                    _ => {
                        let (en, stuck) = self.variant_enum(*op);
                        let vn = o.variant.as_ref().unwrap();
                        let node = if stuck {
                            let st = format!("s{}", self.next());
                            self.out.line(&format!(
                                "let Builtin::Stuck({st}) = {scrut} else {{ {fail} }};"
                            ));
                            st
                        } else {
                            scrut.to_string()
                        };
                        let fields: Vec<String> =
                            args.iter().map(|_| format!("p{}", self.next())).collect();
                        let pat = if fields.is_empty() {
                            format!("{en}::{vn}")
                        } else {
                            format!("{en}::{vn}({})", fields.join(", "))
                        };
                        self.out
                            .line(&format!("let {pat} = &**{node} else {{ {fail} }};"));
                        for ((a, f), &as_) in args.iter().zip(&fields).zip(&o.args) {
                            self.pattern_check(a, f, as_, fail, vars);
                        }
                    }
                }
            }
        }
    }

