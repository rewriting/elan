// Package gen emits the Go source of a compiled program from its IR
// (package elan/ir): a main package importing the runtime elan/elanrt.
//
// Shape of the generated code (readability first: the generated program is
// meant to be read):
//
//   - the runtime symbols of the operators that can be at the top of a
//     normal form (constructors, operators that can be stuck), as
//     constants, declared in that order by init with their printing form;
//   - one function per operator, `func plus_320(a0, a1 rt.Term) rt.Term`,
//     arguments in normal form, result in normal form, with a comment
//     giving its ELAN declaration and rules; terms are rt.Term, and the
//     builtin sorts whose terms cannot be stuck are native Go values
//     (int32, bool, string), boxed only when stored in a term. A defined
//     operator's body is its decision tree (a switch on the head symbol of
//     an argument, or a chain of tests on builtin values), each rule
//     applied in a block of nested ifs (its conditions), then the stuck
//     term (or a panic when the operator is total). The functions on a call
//     cycle guard their depth (rt.Guard, exit status 3 before Go's fatal
//     stack overflow; rt.Unguard at each return, once its value is
//     computed).
//   - per label (S7b): a function in continuation-passing style,
//     `func rl_inc_7(a0 T, k rt.K[T], first bool) bool`: the decision tree
//     of the labelled rules over the whole term, a rule leaf passing its
//     result to k (`return true` when k asks to stop) and going on with
//     the next rules (all of them, in source order; with first, only those
//     of the first rule that has a result: dc);
//   - per named strategy: `func st_go_4(t T, k rt.K[T]) bool`, its body an
//     expression (strat.go): dk as || of the alternatives, a sequence as
//     a continuation (a closure k<n> for the rest), dc/DC and one/ONE with
//     the runtime's DcChoice and OneChoice, repeat* and iterate* through
//     the runtime (rt.RepeatStarDet/IterateStarDet loops for a
//     deterministic step); a deterministic strategy calling itself in tail
//     position is a loop ([ir.IR.TailCalls]);
//   - strategy terms (strat[X]) need nothing more: eval and the rules of
//     strat[X] are ordinary strategies and labels; META (set_of) and the
//     evaluation of the Strategy[X] terms of call "name":X are generated
//     functions (meta.go);
//   - the functions that can recurse (strategies, labels, the
//     normalisation of the operators of a cycle) start with rt.Guard();
//   - conditions `where p := (S) t`: the rest of the rule in the
//     continuation of S (a closure), so that a failing condition asks S
//     for its next result (`return false`); in a normalisation function
//     the first result for which the rule applies is kept;
//   - AC operators (S7c, ac.go): their function merges the elements of
//     its arguments (rt.MergeAC) and gives them to its function over a
//     multiset (op_ac), which takes the AC term (rt.ACTerm: the shared
//     node, or a transient one) and applies their rules to it, then makes
//     it shared (rt.Intern) when it is a normal form; an AC pattern is matched
//     by loops over the elements of its subject (each solution passed to
//     the rest of the rule, the conditions pruning as soon as their
//     variables are bound);
//   - main: the start term, normalised and printed by the runtime driver
//     (rt.Main: options, output, exit statuses), or each result of the
//     start strategy applied to it.
package gen

import (
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
	"unicode/utf8"

	"elan/ir"
)

// GoMod is the go.mod of a generated program: module elanprog, the
// runtime module elan/elanrt from the directory runtime (a replace
// directive: no network, no checksum).
func GoMod(program, runtime string) string {
	return "// Generated by elanc-go for " + comment(program) + ": do not edit.\n" +
		"module elanprog\n\n" +
		"go 1.24\n\n" +
		"require elan/elanrt v0.0.0\n\n" +
		"replace elan/elanrt => " + strconv.Quote(runtime) + "\n"
}

// Main is the main.go of a generated program, formatted by go/format.
func Main(p *ir.IR) ([]byte, error) {
	e := &emitter{ir: p}
	e.file()
	src := []byte(e.b.String())
	out, err := format.Source(src)
	if err != nil {
		return src, fmt.Errorf("generated code does not parse: %v", err)
	}
	return out, nil
}

// emitter writes Go source, indented by tabs.
type emitter struct {
	ir     *ir.IR
	b      strings.Builder
	indent int
	fresh  int  // counter of temporaries in the current function
	b2i    bool // the helper b2i is needed
	// injTests are the injections whose test is needed (injTest)
	injTests []ir.OpID
	// labelMode: the rules are those of a label (each result to k)
	labelMode bool
	// guarded: a normalisation function that counts its depth (rt.Guard):
	// its returns end its level (ret)
	guarded bool
	// res, ok are the variables of the result kept by a normalisation
	// function after a `where p := (S) t`; resType is their type
	res, ok, resType string
	// tail are the tail calls of the strategy emitted as a loop
	tail map[*ir.Strat]bool
	// used are the Go variables that the strategy code emitted so far uses
	// (see use)
	used map[string]bool
	// ext is, inside the matching of a rule applied modulo an extension,
	// the extension (ac.go)
	ext *extension
	// late is, inside the matching of a rule whose AC variable takes the
	// rest of the elements without an extension (ac.go, restTaker), that
	// variable, bound after the conditions
	late *lateRest
	// ekerPats are the patterns of Eker's matcher (ac.go), declared at the
	// end
	ekerPats []string
}

func (e *emitter) line(format string, a ...any) {
	s := fmt.Sprintf(format, a...)
	if s != "" {
		e.b.WriteString(strings.Repeat("\t", e.indent))
		e.b.WriteString(s)
	}
	e.b.WriteByte('\n')
}

func (e *emitter) open(format string, a ...any) {
	e.line(format, a...)
	e.indent++
}

func (e *emitter) close(s string) {
	e.indent--
	e.line("%s", s)
}

func (e *emitter) next() int {
	e.fresh++
	return e.fresh
}

// comment makes text fit in a Go comment (Go sources are UTF-8; ELAN
// names are Latin-1 bytes).
func comment(s string) string {
	if utf8.ValidString(s) {
		return s
	}
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		b.WriteRune(rune(s[i]))
	}
	return b.String()
}

// ---------------------------------------------------------------------------
// Types and values

func goNative(k ir.BuiltinKind) string {
	switch k {
	case ir.KindInt:
		return "int32"
	case ir.KindBool:
		return "bool"
	}
	return "string"
}

// goType is the Go type of the terms of sort s.
func (e *emitter) goType(s ir.SortID) string {
	if k, ok := e.ir.Native(s); ok {
		return goNative(k)
	}
	return "rt.Term"
}

// asTerm is the term of x, the representation of a term of sort s (to be
// stored in a node): a native value is boxed.
func (e *emitter) asTerm(s ir.SortID, x string) string {
	k, ok := e.ir.Native(s)
	if !ok {
		return x
	}
	return boxValue(k, x)
}

// fromValue is the representation in sort s of the native value v of the
// family of s: v itself, or its box when the family is boxed.
func (e *emitter) fromValue(s ir.SortID, v string) string {
	if _, ok := e.ir.Native(s); ok {
		return v
	}
	return boxValue(e.ir.FamilyOf(s).Kind, v)
}

func boxValue(k ir.BuiltinKind, v string) string {
	switch k {
	case ir.KindInt:
		return "rt.MkInt(" + v + ")"
	case ir.KindBool:
		return "rt.MkBool(" + v + ")"
	}
	return "rt.MkStr(" + v + ")"
}

// unbox is the value of sort s held by the term t (a child of a node).
func (e *emitter) unbox(s ir.SortID, t string) string {
	k, ok := e.ir.Native(s)
	if !ok {
		return t
	}
	switch k {
	case ir.KindInt:
		return t + ".Int"
	case ir.KindBool:
		return t + " == rt.True"
	}
	return "rt.StrOf(" + t + ")"
}

func symName(op *ir.Op) string { return "sym_" + op.Fun }

// eqExpr is the test that a and b, of sort s, are the same term: rt.Eq
// on terms (int nodes are not shared), == on native values.
func (e *emitter) eqExpr(s ir.SortID, a, b string) string {
	if _, ok := e.ir.Native(s); ok {
		return a + " == " + b
	}
	return "rt.Eq(" + a + ", " + b + ")"
}

// acFun is the normalisation function of the AC operator op over a
// multiset; nil for a constructor (rt.ApplyAC and rt.ExtendAC then
// build the term).
func acFun(op *ir.Op) string {
	if op.Kind != ir.Defined {
		return "nil"
	}
	return op.ACFun
}

// mk is the construction of the term o(args), args being terms.
func (e *emitter) mk(o ir.OpID, args []string) string {
	sym := symName(&e.ir.Ops[o])
	if e.ir.Ops[o].AC {
		// flattened and sorted
		return "rt.MkAC2(" + sym + ", " + strings.Join(args, ", ") + ")"
	}
	switch len(args) {
	case 0:
		return "rt.Mk0(" + sym + ")"
	case 1, 2, 3:
		return fmt.Sprintf("rt.Mk%d(%s, %s)", len(args), sym, strings.Join(args, ", "))
	}
	return "rt.Mk(" + sym + ", " + strings.Join(args, ", ") + ")"
}

// stuck is the term o(a0, ...) of the function's arguments.
func (e *emitter) stuck(o ir.OpID) string {
	op := &e.ir.Ops[o]
	var args []string
	for i, s := range op.Args {
		args = append(args, e.asTerm(s, fmt.Sprintf("a%d", i)))
	}
	return e.mk(o, args)
}

func goInt(n int32) string { return strconv.FormatInt(int64(n), 10) }

// goString is a Go literal of a byte string (bytes above 127 escaped).
func goString(s string) string { return strconv.Quote(s) }

// expr is an expression computing the normal form of x.
func (e *emitter) expr(x *ir.Expr, vars []ir.Var) string {
	switch x.Kind {
	case ir.ExprVar:
		return vars[x.Var].Name
	case ir.ExprInt:
		return e.fromValue(e.ir.ExprSort(x, vars), goInt(x.Int))
	case ir.ExprStr:
		return e.fromValue(e.ir.ExprSort(x, vars), goString(x.Str))
	}
	op := &e.ir.Ops[x.Op]
	switch op.Kind {
	case ir.Injection:
		return e.expr(&x.Args[0], vars)
	case ir.BoolConst:
		if _, ok := e.ir.Native(op.Result); ok {
			return strconv.FormatBool(op.Bool)
		}
		if op.Bool {
			return "rt.True"
		}
		return "rt.False"
	}
	if op.AC {
		if args := e.acArgs(x, vars); len(args) > 2 {
			// one AC term: normalised once, as a whole
			return fmt.Sprintf("rt.ApplyAC(%s, %s, %s)", symName(op), acFun(op), strings.Join(args, ", "))
		}
	}
	var args []string
	for i := range x.Args {
		args = append(args, e.expr(&x.Args[i], vars))
	}
	return op.Fun + "(" + strings.Join(args, ", ") + ")"
}

// acArgs are the expressions of the arguments of the AC operator at the
// top of x, the nested applications of the same operator flattened: the
// interpreter flattens an AC term before normalising it (its subterms of
// the same operator are not redexes of their own: F(a, F(b, c)) is
// normalised as the multiset a, b, c, as REM does).
func (e *emitter) acArgs(x *ir.Expr, vars []ir.Var) []string {
	var args []string
	for i := range x.Args {
		a := &x.Args[i]
		if a.Kind == ir.ExprOp && a.Op == x.Op {
			args = append(args, e.acArgs(a, vars)...)
		} else {
			args = append(args, e.expr(a, vars))
		}
	}
	return args
}

// typedExpr is expr, an int literal typed int32 (for `x := ...`).
func (e *emitter) typedExpr(x *ir.Expr, vars []ir.Var) string {
	s := e.expr(x, vars)
	if _, err := strconv.Atoi(s); err == nil {
		return "int32(" + s + ")"
	}
	return s
}

// headTest is the test that the term or value t of sort s has head h; ""
// when it always has (an injection into a native family).
func (e *emitter) headTest(s ir.SortID, t string, h ir.Head) string {
	_, native := e.ir.Native(s)
	switch h.Kind {
	case ir.HeadInt:
		if native {
			return t + " == " + goInt(h.Int)
		}
		return "rt.IsInt(" + t + ") && " + t + ".Int == " + goInt(h.Int)
	case ir.HeadStr:
		if native {
			return t + " == " + goString(h.Str)
		}
		return "rt.IsStr(" + t + ") && rt.StrOf(" + t + ") == " + goString(h.Str)
	}
	op := &e.ir.Ops[h.Op]
	switch op.Kind {
	case ir.BoolConst:
		switch {
		case native && op.Bool:
			return t
		case native:
			return "!" + t
		case op.Bool:
			return t + " == rt.True"
		}
		return t + " == rt.False"
	case ir.Injection:
		if native {
			return ""
		}
		if len(e.otherStuck(h.Op)) == 0 {
			return ""
		}
		if !slices.Contains(e.injTests, h.Op) {
			e.injTests = append(e.injTests, h.Op)
		}
		return "is_" + op.Fun + "(" + t + ")"
	}
	return t + ".Sym == " + symName(op)
}

// otherStuck are the operators whose stuck terms are terms of the sort of
// the injection inj, but not injections (their sort is not the builtin
// sort).
func (e *emitter) otherStuck(inj ir.OpID) []ir.OpID {
	op := &e.ir.Ops[inj]
	var v []ir.OpID
	for _, o := range e.ir.FamilyOf(op.Result).Stuck {
		if e.ir.Ops[o].Result != op.Args[0] {
			v = append(v, o)
		}
	}
	return v
}

// injTest writes the test of a pattern inj(x) on the boxed terms of the
// sort of the injection inj: a term of that sort is a value, a stuck term
// of the builtin sort (both the injection of a builtin term) or a stuck
// term of the sort itself (not an injection).
func (e *emitter) injTest(inj ir.OpID) {
	op := &e.ir.Ops[inj]
	var syms []string
	for _, o := range e.otherStuck(inj) {
		syms = append(syms, symName(&e.ir.Ops[o]))
	}
	e.line("// is_%s tells whether t, of sort %s, is the injection %s of a term", op.Fun,
		comment(e.ir.Sorts[op.Result].Name), op.Fun)
	e.line("// of sort %s (a value or a stuck term of that sort).", comment(e.ir.Sorts[op.Args[0]].Name))
	e.open("func is_%s(t rt.Term) bool {", op.Fun)
	e.line("switch t.Sym {")
	e.line("case %s:", strings.Join(syms, ", "))
	e.line("\treturn false")
	e.line("}")
	e.line("return true")
	e.close("}")
	e.line("")
}

// ---------------------------------------------------------------------------
// The file

func (e *emitter) file() {
	p := e.ir
	e.line("// Code generated by elanc-go from %s.ref. DO NOT EDIT.", comment(p.Program))
	e.line("")
	e.line("// Normalisation (innermost) of the start term of %s with its unlabelled", comment(p.Program))
	e.line("// rules: one function per operator, its arguments in normal form.")
	if p.Start.Strategy >= 0 {
		e.line("// Then the strategy %s: each label and each strategy is a function", comment(p.Strategies[p.Start.Strategy].Name))
		e.line("// passing its results to a continuation k.")
	}
	e.line("package main")
	e.line("")
	e.line(`import rt "elan/elanrt"`)
	e.line("")
	e.sorts()
	e.symbols()
	e.line("// ==== operators ====")
	e.line("")
	for o := range p.Ops {
		e.opFunc(o)
	}
	e.labels()
	e.strategies()
	e.metas()
	for _, o := range e.injTests {
		e.injTest(o)
	}
	if e.b2i {
		e.line("// b2i orders the booleans as C ints (false < true).")
		e.open("func b2i(b bool) int32 {")
		e.open("if b {")
		e.line("return 1")
		e.close("}")
		e.line("return 0")
		e.close("}")
		e.line("")
	}
	e.ekerDecls()
	e.mainFunc()
}

// sorts writes a comment per sort: its representation.
func (e *emitter) sorts() {
	p := e.ir
	e.line("// ==== sorts ====")
	e.line("//")
	for s := range p.Sorts {
		sort := &p.Sorts[s]
		if f := p.FamilyOf(s); f != nil {
			how := "builtin"
			if f.Base != s {
				how = "injection of " + p.Sorts[f.Base].Name
			}
			repr := goNative(f.Kind)
			if f.Boxed() {
				var ops []string
				for _, o := range f.Stuck {
					ops = append(ops, p.Ops[o].Fun)
				}
				repr = "rt.Term (a boxed " + goNative(f.Kind) + " or a stuck term: " + strings.Join(ops, ", ") + ")"
			}
			e.line("// sort %s (%s): %s", comment(sort.Name), how, repr)
			continue
		}
		var vs []string
		for _, o := range sort.Variants {
			vs = append(vs, p.Ops[o].Fun)
		}
		e.line("// sort %s: rt.Term with head %s", comment(sort.Name), strings.Join(vs, ", "))
	}
	e.line("")
}

func printItem(it ir.PrintItem) string {
	switch it.Kind {
	case ir.PArg:
		return fmt.Sprintf("rt.Arg(%d)", it.Arg)
	case ir.PIdent:
		return "rt.Ident(" + goString(it.Text) + ")"
	case ir.PNum:
		return fmt.Sprintf("rt.Num(%d)", it.Num)
	}
	c := it.Char
	if c >= 0x20 && c < 0x7f && c != '\'' && c != '\\' {
		return "rt.Char('" + string(c) + "')"
	}
	return fmt.Sprintf("rt.Char(0x%02x)", c)
}

// symbols writes the runtime symbols.
func (e *emitter) symbols() {
	p := e.ir
	var syms []ir.OpID
	for o := range p.Ops {
		if p.Ops[o].Variant {
			syms = append(syms, o)
		}
	}
	if len(syms) == 0 {
		return
	}
	e.line("// ==== runtime symbols ====")
	e.line("")
	e.line("// The symbols of the terms (constructors and operators that can be")
	e.line("// stuck), declared to the runtime in this order by init.")
	e.open("const (")
	for i, o := range syms {
		op := &p.Ops[o]
		if i == 0 {
			e.line("%s int32 = rt.SymFalse + 1 + iota // %s", symName(op), comment(op.Decl))
		} else {
			e.line("%s // %s", symName(op), comment(op.Decl))
		}
	}
	e.close(")")
	e.line("")
	e.open("func init() {")
	for _, o := range syms {
		op := &p.Ops[o]
		var items []string
		for _, it := range op.Print {
			items = append(items, printItem(it))
		}
		e.line("declare(%s, %q, %d, %v, %d, %s)", symName(op), op.Fun, len(op.Args), op.AC, op.Symbol, strings.Join(items, ", "))
	}
	e.close("}")
	e.line("")
	e.line("// declare adds a symbol (AC or not, its code in the .ref file: the order of")
	e.line("// terms) and its printing form to the runtime's table, at the code of its")
	e.line("// constant.")
	e.open("func declare(code int32, name string, arity int, ac bool, refCode int32, layout ...rt.PrintItem) {")
	e.open("if rt.DeclareSym(rt.Symbol{Name: name, Arity: arity, AC: ac, Code: refCode, Print: layout}) != code {")
	e.line(`panic("symbol " + name + " declared out of order")`)
	e.close("}")
	e.close("}")
	e.line("")
}

func (e *emitter) signature(o ir.OpID) string {
	op := &e.ir.Ops[o]
	var params []string
	for i, s := range op.Args {
		params = append(params, fmt.Sprintf("a%d %s", i, e.goType(s)))
	}
	return fmt.Sprintf("func %s(%s) %s", op.Fun, strings.Join(params, ", "), e.goType(op.Result))
}

func (e *emitter) opFunc(o ir.OpID) {
	op := &e.ir.Ops[o]
	e.fresh = 0
	decl := comment(op.Decl)
	switch op.Kind {
	case ir.Constructor:
		e.line("// %s: %s (constructor).", op.Fun, decl)
		e.open("%s {", e.signature(o))
		e.line("return %s", e.stuck(o))
		e.close("}")
	case ir.Injection:
		e.line("// %s: %s (injection: the identity).", op.Fun, decl)
		e.open("%s {", e.signature(o))
		e.line("return a0")
		e.close("}")
	case ir.BoolConst:
		e.line("// %s: %s.", op.Fun, decl)
		e.open("%s {", e.signature(o))
		e.line("return %s", e.expr(&ir.Expr{Kind: ir.ExprOp, Op: o}, nil))
		e.close("}")
	case ir.Builtin:
		how := ""
		if !op.Total {
			how = ", may stay stuck"
		}
		e.line("// %s: %s (builtin %v%s).", op.Fun, decl, op.Builtin, how)
		e.open("%s {", e.signature(o))
		e.builtinBody(o)
		e.close("}")
	case ir.Defined:
		how := ""
		if !op.Total {
			how = " (stuck when no rule applies)"
		}
		e.line("// %s: %s%s.", op.Fun, decl, how)
		e.line("//")
		for _, r := range op.Rules {
			e.line("//\t%s", comment(r.Text))
		}
		for _, s := range op.Skipped {
			e.line("//\tskipped: %s", comment(s))
		}
		if op.AC {
			e.open("%s {", e.signature(o))
			e.line("return %s(rt.MergeAC(%s, a0, a1))", acFun(op), symName(op))
			e.close("}")
			e.line("")
			e.line("// %s: the normal form of the AC term of %s over the elements e", acFun(op), op.Fun)
			e.line("// (flattened, sorted, two or more; kept).")
			e.open("func %s(e []rt.Term) rt.Term {", acFun(op))
		} else {
			e.open("%s {", e.signature(o))
		}
		e.guarded = op.Recursive
		e.resType = e.goType(op.Result)
		if op.Recursive {
			e.line("rt.Guard() // (each return calls rt.Unguard)")
		}
		if op.AC {
			e.line("// the AC term (shared, or transient until it is a normal form): the")
			e.line("// only column of the rules")
			e.line("a0 := rt.ACTerm(%s, e)", symName(op))
			e.open("if rt.Normal(a0) {")
			e.line("// a normal form found before, without a step")
			e.ret("a0")
			e.close("}")
		}
		mark := e.b.Len()
		if op.AC {
			e.line("steps := rt.Steps")
		}
		e.resType = e.goType(op.Result)
		falls := e.decision(op.Tree, op.Rules)
		if op.AC && (!falls || op.Total) {
			// steps is not used: no line
			s := e.b.String()
			e.b.Reset()
			e.b.WriteString(s[:mark])
			e.b.WriteString(s[strings.IndexByte(s[mark:], '\n')+mark+1:])
		}
		switch {
		case !falls:
			// (the code ends with a return: go vet refuses unreachable code)
		case op.Total:
			e.line(`panic("%s: no rule applies to a total operator")`, op.Fun)
		case op.AC:
			e.line("// no rule applies: the term is a normal form")
			e.ret("rt.NormalForm(a0, steps)")
		default:
			e.line("// no rule applies: the term is a normal form")
			e.ret(e.stuck(o))
		}
		e.guarded = false
		e.close("}")
	}
	e.line("")
}

// ret writes the return of x from a normalisation function; a guarded
// one ends its level once x is computed (x can recurse). (rt.Unguard is
// called at each return rather than deferred: a deferred call is not
// inlined, ~5 % of nqueens.)
func (e *emitter) ret(x string) {
	if !e.guarded {
		e.line("return %s", x)
		return
	}
	if isIdent(x) {
		e.line("rt.Unguard()")
		e.line("return %s", x)
		return
	}
	r := fmt.Sprintf("ret%d", e.next())
	e.line("var %s %s = %s", r, e.resType, x)
	e.line("rt.Unguard()")
	e.line("return %s", r)
}

// isIdent tells whether x is a Go identifier (a variable: no call).
func isIdent(x string) bool {
	for i, c := range x {
		if !(c == '_' || 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || i > 0 && '0' <= c && c <= '9') {
			return false
		}
	}
	return x != ""
}

func (e *emitter) builtinBody(o ir.OpID) {
	op := &e.ir.Ops[o]
	b := op.Builtin
	res := op.Result
	if !b.NeedsValues() {
		isTrue := func(i int) string {
			if _, ok := e.ir.Native(op.Args[i]); ok {
				return fmt.Sprintf("a%d", i)
			}
			return fmt.Sprintf("a%d == rt.True", i)
		}
		var v string
		switch b {
		case ir.TermEq:
			v = e.eqExpr(op.Args[0], "a0", "a1")
		case ir.TermNeq:
			v = "!" + e.eqExpr(op.Args[0], "a0", "a1")
		case ir.BoolAnd:
			v = isTrue(0) + " && " + isTrue(1)
		case ir.BoolOr:
			v = isTrue(0) + " || " + isTrue(1)
		case ir.BoolNot:
			v = "!(" + isTrue(0) + ")"
		}
		e.line("return %s", e.fromValue(res, v))
		return
	}
	// the values of the arguments: vi, or ai when native
	vals := make([]string, len(op.Args))
	var oks []string
	for i, s := range op.Args {
		f := e.ir.FamilyOf(s)
		if !f.Boxed() {
			vals[i] = fmt.Sprintf("a%d", i)
			continue
		}
		vals[i] = fmt.Sprintf("v%d", i)
		a := fmt.Sprintf("a%d", i)
		if op.Total {
			// a boxed family whose terms of this sort are values: checked
			// (a stuck term would be a bug, a panic naming the operator)
			e.line("v%d := %s", i, e.unboxValue(f.Kind, a, op.Fun))
			continue
		}
		get := map[ir.BuiltinKind]string{ir.KindInt: "rt.IntOf", ir.KindBool: "rt.BoolOf", ir.KindStr: "rt.StrValue"}[f.Kind]
		e.line("v%d, ok%d := %s(%s)", i, i, get, a)
		oks = append(oks, fmt.Sprintf("!ok%d", i))
	}
	if len(oks) > 0 {
		e.open("if %s {", strings.Join(oks, " || "))
		e.line("return %s // a stuck argument", e.stuck(o))
		e.close("}")
	}
	v := vals
	var value string
	switch b {
	case ir.IntAdd:
		value = v[0] + " + " + v[1]
	case ir.IntSub:
		value = v[0] + " - " + v[1]
	case ir.IntMul:
		value = v[0] + " * " + v[1]
	case ir.IntDiv:
		value = "rt.Div(" + v[0] + ", " + v[1] + ")"
	case ir.IntRem:
		value = "rt.Mod(" + v[0] + ", " + v[1] + ")"
	case ir.IntAnd:
		value = v[0] + " & " + v[1]
	case ir.IntOr:
		value = v[0] + " | " + v[1]
	case ir.IntNeg:
		value = "-" + v[0]
	case ir.CmpEq, ir.CmpNe, ir.CmpLt, ir.CmpLe, ir.CmpGt, ir.CmpGe:
		cmp := map[ir.BuiltinOp]string{ir.CmpEq: "==", ir.CmpNe: "!=", ir.CmpLt: "<", ir.CmpLe: "<=", ir.CmpGt: ">", ir.CmpGe: ">="}[b]
		x, y := v[0], v[1]
		if e.ir.FamilyOf(op.Args[0]).Kind == ir.KindBool && b != ir.CmpEq && b != ir.CmpNe {
			x, y = "b2i("+x+")", "b2i("+y+")"
			e.b2i = true
		}
		value = x + " " + cmp + " " + y
	case ir.StrLen:
		value = "rt.StrLen(" + v[0] + ")"
	case ir.StrCat:
		value = "rt.StrCat(" + v[0] + ", " + v[1] + ")"
	case ir.StrSpn:
		value = "rt.StrSpn(" + v[0] + ", " + v[1] + ")"
	case ir.StrCmp:
		value = "rt.StrCmp(" + v[0] + ", " + v[1] + ")"
	case ir.StrOfChar:
		value = "rt.StrOfChar(" + v[0] + ")"
	case ir.StrIndex:
		value = "rt.StrIndex(" + v[0] + ", " + v[1] + ")"
	case ir.StrModif:
		value = "rt.StrModif(" + v[0] + ", " + v[1] + ", " + v[2] + ")"
	case ir.StrSubstr:
		value = "rt.StrSubstr(" + v[0] + ", " + v[1] + ", " + v[2] + ")"
	}
	if b.Partial() {
		e.open("if r, ok := %s; ok {", value)
		e.line("return %s", e.fromValue(res, "r"))
		e.close("}")
		e.line("return %s // undefined on these values", e.stuck(o))
		return
	}
	e.line("return %s", e.fromValue(res, value))
}

// unboxValue is the value of kind k of the boxed value t received by the
// function fun (checked: rt.MustInt...).
func (e *emitter) unboxValue(k ir.BuiltinKind, t, fun string) string {
	get := map[ir.BuiltinKind]string{ir.KindInt: "rt.MustInt", ir.KindBool: "rt.MustBool", ir.KindStr: "rt.MustStr"}[k]
	return fmt.Sprintf("%s(%s, %s)", get, t, goString(fun))
}

