// The file

func (e *emitter) file() {
	p := e.ir
	e.line("// Code generated by elanc-go from %s.ref. DO NOT EDIT.", comment(p.Program))
	e.line("")
	e.line("// Normalisation (innermost) of the start term of %s with its unlabelled", comment(p.Program))
	e.line("// rules: one function per operator, its arguments in normal form.")
	if p.Start.Strategy >= 0 {
		e.line("// Then the strategy %s: each label and each strategy is a function", comment(p.Strategies[p.Start.Strategy].Name))
		e.line("// passing its results to a continuation k.")
	}
	e.line("package main")
	e.line("")
	if p.Start.Query != nil {
		e.open("import (")
		e.line(`"strconv"`)
		e.line("")
		e.line(`rt "elan/elanrt"`)
		e.line(`"elan/elanrt/earley"`)
		e.close(")")
	} else {
		e.line(`import rt "elan/elanrt"`)
	}
	e.line("")
	e.sorts()
	e.symbols()
	e.line("// ==== operators ====")
	e.line("")
	for o := range p.Ops {
		e.opFunc(o)
	}
	e.labels()
	e.strategies()
	e.metas()
	e.travFuncs()
	for _, o := range e.injTests {
		e.injTest(o)
	}
	if e.b2i {
		e.line("// b2i orders the booleans as C ints (false < true).")
		e.open("func b2i(b bool) int32 {")
		e.open("if b {")
		e.line("return 1")
		e.close("}")
		e.line("return 0")
		e.close("}")
		e.line("")
	}
	if e.normTerm {
		e.normTermFunc()
	}
	e.ekerDecls()
	e.query()
	e.mainFunc()
}

// query writes the query parser's tables (S7d task 5): the grammar
// (REM's gram[]), the names of the sorts, and the functions building the
// term of each grammar rule (queryOp, queryAC, queryIsAC).
func (e *emitter) query() {
	q := e.ir.Start.Query
	if q == nil {
		return
	}
	p := e.ir
	e.line("// ==== query ====")
	e.line("")
	e.line("// grammar is the grammar of the query parser (REM's gram[]: the grammar")
	e.line("// rules of the .ref file).")
	e.open("var grammar = []earley.Rule{")
	for _, g := range q.Grammar {
		var rhs []string
		for _, x := range g.Rhs {
			rhs = append(rhs, fmt.Sprintf("{Kind: %d, Code: %d}", x.Kind, x.Code))
		}
		e.line("{Sort: %d, Symbol: %d, Info: %d, Rhs: []earley.RhsLexem{%s}},", g.Sort, g.Symbol, g.Info, strings.Join(rhs, ", "))
	}
	e.close("}")
	e.line("")
	e.line("// sortNames are the names of the sorts (warnings of the parser).")
	e.open("var sortNames = map[int32]string{")
	names := slices.Sorted(maps.Keys(q.SortNames))
	for _, s := range names {
		e.line("%d: %s,", s, goString(q.SortNames[s]))
	}
	e.close("}")
	e.line("")
	// the rules built by the function of one operator, by operator
	byOp := map[ir.OpID][]int{}
	var ops []ir.OpID
	var umin, unsupported []int
	for r, x := range q.Rules {
		switch x.Kind {
		case ir.QueryOp:
			if _, ok := byOp[x.Op]; !ok {
				ops = append(ops, x.Op)
			}
			byOp[x.Op] = append(byOp[x.Op], r)
		case ir.QueryUmin:
			umin = append(umin, r)
		case ir.QueryUnsupported:
			unsupported = append(unsupported, r)
		}
	}
	cases := func(rs []int) string {
		var c []string
		for _, r := range rs {
			c = append(c, strconv.Itoa(r))
		}
		return "case " + strings.Join(c, ", ") + ":"
	}
	e.line("// queryOp is the normal form of the operator of grammar rule r applied to")
	e.line("// a (terms in normal form).")
	e.open("func queryOp(r int, a []rt.Term) rt.Term {")
	e.line("switch r {")
	for _, o := range ops {
		op := &p.Ops[o]
		if op.AC {
			continue
		}
		e.line("%s // %s", cases(byOp[o]), comment(op.Decl))
		e.indent++
		x := ir.Expr{Kind: ir.ExprOp, Op: o}
		var vars []ir.Var
		for i, s := range op.Args {
			x.Args = append(x.Args, ir.Expr{Kind: ir.ExprVar, Var: i})
			vars = append(vars, ir.Var{Name: e.unbox(s, fmt.Sprintf("a[%d]", i)), Sort: s})
		}
		e.line("return %s", e.asTerm(op.Result, e.expr(&x, vars)))
		e.indent--
	}
	if len(umin) > 0 {
		e.line("%s // - n (INTCONSTUMIN)", cases(umin))
		e.line("\treturn rt.MkInt(-a[0].Int)")
	}
	e.line("}")
	e.line("queryUnsupported(r)")
	e.line("return nil")
	e.close("}")
	e.line("")
	e.line("// queryAC is the normal form of the AC operator of grammar rule r applied")
	e.line("// to the elements a (in normal form).")
	e.open("func queryAC(r int, a []rt.Term) rt.Term {")
	e.line("switch r {")
	var acRules []int
	for _, o := range ops {
		op := &p.Ops[o]
		if !op.AC {
			continue
		}
		acRules = append(acRules, byOp[o]...)
		e.line("%s // %s", cases(byOp[o]), comment(op.Decl))
		e.line("\treturn rt.ApplyAC(%s, %s, a...)", symName(op), acFun(op))
	}
	e.line("}")
	e.line("queryUnsupported(r)")
	e.line("return nil")
	e.close("}")
	e.line("")
	e.line("// queryIsAC tells whether the operator of grammar rule r is AC.")
	e.open("func queryIsAC(r int) bool {")
	if len(acRules) > 0 {
		e.line("switch r {")
		e.line("%s", cases(acRules))
		e.line("\treturn true")
		e.line("}")
	}
	e.line("return false")
	e.close("}")
	e.line("")
	e.line("// queryUnsupported stops a query with an operator that is not compiled.")
	e.open("func queryUnsupported(r int) {")
	e.line("why := \"\"")
	if len(unsupported) > 0 {
		e.line("switch r {")
		for _, r := range unsupported {
			e.line("case %d:", r)
			e.line("\twhy = %s", goString(": "+q.Rules[r].Why))
		}
		e.line("}")
	}
	e.line("rt.Unsupported(\"a query with the operator of grammar rule \" + strconv.Itoa(r) + why)")
	e.close("}")
	e.line("")
}

// normTermFunc writes normTerm, the normalisation dispatcher of rt.Replace:
// the normal form of sym(args...), its arguments in normal form (an AC
// symbol: its elements), by the function of the operator for the symbols
// of the operators that can be stuck (defined or builtin), else the term
// (a constructor).
func (e *emitter) normTermFunc() {
	p := e.ir
	e.line("// normTerm is the normal form of sym(a...), a in normal form (the elements")
	e.line("// of an AC term): the function of its operator, or the term of a")
	e.line("// constructor (rt.Replace renormalises the path it copies).")
	e.open("func normTerm(sym int32, a []rt.Term) rt.Term {")
	e.line("switch sym {")
	for o := range p.Ops {
		op := &p.Ops[o]
		if !op.Variant || op.Kind == ir.Constructor {
			continue
		}
		e.line("case %s:", symName(op))
		e.indent++
		if op.AC {
			e.line("return %s(a)", acFun(op))
		} else {
			var args []string
			for i, s := range op.Args {
				args = append(args, e.unbox(s, fmt.Sprintf("a[%d]", i)))
			}
			e.line("return %s", e.asTerm(op.Result, op.Fun+"("+strings.Join(args, ", ")+")"))
		}
		e.indent--
	}
	e.line("}")
	e.line("return rt.MkAny(sym, a)")
	e.close("}")
	e.line("")
}

// sorts writes a comment per sort: its representation.
func (e *emitter) sorts() {
	p := e.ir
	e.line("// ==== sorts ====")
	e.line("//")
	for s := range p.Sorts {
		sort := &p.Sorts[s]
		if f := p.FamilyOf(s); f != nil {
			how := "builtin"
			if f.Base != s {
				how = "injection of " + p.Sorts[f.Base].Name
			}
			repr := goNative(f.Kind)
			if f.Boxed() {
				var ops []string
				for _, o := range f.Stuck {
					ops = append(ops, p.Ops[o].Fun)
				}
				repr = "rt.Term (a boxed " + goNative(f.Kind) + " or a stuck term: " + strings.Join(ops, ", ") + ")"
			}
			e.line("// sort %s (%s): %s", comment(sort.Name), how, repr)
			continue
		}
		var vs []string
		for _, o := range sort.Variants {
			vs = append(vs, p.Ops[o].Fun)
		}
		e.line("// sort %s: rt.Term with head %s", comment(sort.Name), strings.Join(vs, ", "))
	}
	e.line("")
}

func printItem(it ir.PrintItem) string {
	switch it.Kind {
	case ir.PArg:
		return fmt.Sprintf("rt.Arg(%d)", it.Arg)
	case ir.PIdent:
		return "rt.Ident(" + goString(it.Text) + ")"
	case ir.PNum:
		return fmt.Sprintf("rt.Num(%d)", it.Num)
	}
	c := it.Char
	if c >= 0x20 && c < 0x7f && c != '\'' && c != '\\' {
		return "rt.Char('" + string(c) + "')"
	}
	return fmt.Sprintf("rt.Char(0x%02x)", c)
}

// symbols writes the runtime symbols.
func (e *emitter) symbols() {
	p := e.ir
	var syms []ir.OpID
	for o := range p.Ops {
		if p.Ops[o].Variant {
			syms = append(syms, o)
		}
	}
	if len(syms) == 0 {
		return
	}
	e.line("// ==== runtime symbols ====")
	e.line("")
	e.line("// The symbols of the terms (constructors and operators that can be")
	e.line("// stuck), declared to the runtime in this order by init.")
	e.open("const (")
	for i, o := range syms {
		op := &p.Ops[o]
		if i == 0 {
			e.line("%s int32 = rt.FirstSym + iota // %s", symName(op), comment(op.Decl))
		} else {
			e.line("%s // %s", symName(op), comment(op.Decl))
		}
	}
	e.close(")")
	e.line("")
	e.open("func init() {")
	for _, o := range syms {
		op := &p.Ops[o]
		var items []string
		for _, it := range op.Print {
			items = append(items, printItem(it))
		}
		e.line("declare(%s, %q, %d, %v, %d, %s)", symName(op), op.Fun, len(op.Args), op.AC, op.Symbol, strings.Join(items, ", "))
	}
	e.close("}")
	e.line("")
	e.line("// declare adds a symbol (AC or not, its code in the .ref file: the order of")
	e.line("// terms) and its printing form to the runtime's table, at the code of its")
	e.line("// constant.")
	e.open("func declare(code int32, name string, arity int, ac bool, refCode int32, layout ...rt.PrintItem) {")
	e.open("if rt.DeclareSym(rt.Symbol{Name: name, Arity: arity, AC: ac, Code: refCode, Print: layout}) != code {")
	e.line(`panic("symbol " + name + " declared out of order")`)
	e.close("}")
	e.close("}")
	e.line("")
}

func (e *emitter) signature(o ir.OpID) string {
	op := &e.ir.Ops[o]
	var params []string
	for i, s := range op.Args {
		params = append(params, fmt.Sprintf("a%d %s", i, e.goType(s)))
	}
	return fmt.Sprintf("func %s(%s) %s", op.Fun, strings.Join(params, ", "), e.goType(op.Result))
}

func (e *emitter) opFunc(o ir.OpID) {
	op := &e.ir.Ops[o]
	e.fresh = 0
	decl := comment(op.Decl)
	switch op.Kind {
	case ir.Constructor:
		e.line("// %s: %s (constructor).", op.Fun, decl)
		e.open("%s {", e.signature(o))
		e.line("return %s", e.stuck(o))
		e.close("}")
	case ir.Injection:
		e.line("// %s: %s (injection: the identity).", op.Fun, decl)
		e.open("%s {", e.signature(o))
		e.line("return a0")
		e.close("}")
	case ir.BoolConst:
		e.line("// %s: %s.", op.Fun, decl)
		e.open("%s {", e.signature(o))
		e.line("return %s", e.expr(&ir.Expr{Kind: ir.ExprOp, Op: o}, nil))
		e.close("}")
	case ir.Builtin:
		how := ""
		if !op.Total {
			how = ", may stay stuck"
		}
		e.line("// %s: %s (builtin %v%s).", op.Fun, decl, op.Builtin, how)
		e.open("%s {", e.signature(o))
		e.builtinBody(o)
		e.close("}")
	case ir.Defined:
		how := ""
		if !op.Total {
			how = " (stuck when no rule applies)"
		}
		e.line("// %s: %s%s.", op.Fun, decl, how)
		e.line("//")
		for _, r := range op.Rules {
			e.line("//\t%s", comment(r.Text))
		}
		for _, s := range op.Skipped {
			e.line("//\tskipped: %s", comment(s))
		}
		if op.AC {
			e.open("%s {", e.signature(o))
			e.line("return %s(rt.MergeAC(%s, a0, a1))", acFun(op), symName(op))
			e.close("}")
			e.line("")
			e.line("// %s: the normal form of the AC term of %s over the elements e", acFun(op), op.Fun)
			e.line("// (flattened, sorted, two or more; kept).")
			e.open("func %s(e []rt.Term) rt.Term {", acFun(op))
		} else {
			e.open("%s {", e.signature(o))
		}
		e.guarded = op.Recursive
		e.resType = e.goType(op.Result)
		if op.Recursive {
			e.line("rt.Guard() // (each return calls rt.Unguard)")
		}
		if op.AC {
			e.line("// the AC term (shared, or transient until it is a normal form): the")
			e.line("// only column of the rules")
			e.line("a0 := rt.ACTerm(%s, e)", symName(op))
			e.open("if rt.Normal(a0) {")
			e.line("// a normal form found before, without a step")
			e.ret("a0")
			e.close("}")
		}
		mark := e.b.Len()
		if op.AC {
			e.line("steps := rt.Steps")
		}
		e.resType = e.goType(op.Result)
		falls := e.decision(op.Tree, op.Rules)
		if op.AC && (!falls || op.Total) {
			// steps is not used: no line
			s := e.b.String()
			e.b.Reset()
			e.b.WriteString(s[:mark])
			e.b.WriteString(s[strings.IndexByte(s[mark:], '\n')+mark+1:])
		}
		switch {
		case !falls:
			// (the code ends with a return: go vet refuses unreachable code)
		case op.Total:
			e.line(`panic("%s: no rule applies to a total operator")`, op.Fun)
		case op.AC:
			e.line("// no rule applies: the term is a normal form")
			e.ret("rt.NormalForm(a0, steps)")
		default:
			e.line("// no rule applies: the term is a normal form")
			e.ret(e.stuck(o))
		}
		e.guarded = false
		e.close("}")
	}
	e.line("")
}

// ret writes the return of x from a normalisation function; a guarded
// one ends its level once x is computed (x can recurse). (rt.Unguard is
// called at each return rather than deferred: a deferred call is not
// inlined, ~5 % of nqueens.)
func (e *emitter) ret(x string) {
	if !e.guarded {
		e.line("return %s", x)
		return
	}
	if isIdent(x) {
		e.line("rt.Unguard()")
		e.line("return %s", x)
		return
	}
	r := fmt.Sprintf("ret%d", e.next())
	e.line("var %s %s = %s", r, e.resType, x)
	e.line("rt.Unguard()")
	e.line("return %s", r)
}

// isIdent tells whether x is a Go identifier (a variable: no call).
func isIdent(x string) bool {
	for i, c := range x {
		if !(c == '_' || 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || i > 0 && '0' <= c && c <= '9') {
			return false
		}
	}
	return x != ""
}

func (e *emitter) builtinBody(o ir.OpID) {
	op := &e.ir.Ops[o]
	b := op.Builtin
	res := op.Result
	if b.OnTerms() {
		// on terms of any sorts: the arguments as terms, except the int
		// values (a file number, an index, a size: the term stays when
		// one is not a value)
		args := make([]string, len(op.Args))
		for i, s := range op.Args {
			args[i] = e.asTerm(s, fmt.Sprintf("a%d", i))
		}
		for _, i := range b.IntArgs() {
			a := fmt.Sprintf("a%d", i)
			args[i] = a
			f := e.ir.FamilyOf(op.Args[i])
			if !f.Boxed() {
				continue
			}
			if op.Total {
				args[i] = e.unboxValue(f.Kind, a, op.Fun)
				continue
			}
			args[i] = fmt.Sprintf("v%d", i)
			e.line("v%d, ok%d := rt.IntOf(%s)", i, i, a)
			e.open("if !ok%d {", i)
			e.line("return %s // a stuck argument", e.stuck(o))
			e.close("}")
		}
		switch b {
		case ir.TermReplace:
			// replace a0 by a1 in a2, the copied path renormalised
			e.normTerm = true
			e.line("return %s", e.unbox(res, "rt.Replace("+args[2]+", "+args[0]+", "+args[1]+", normTerm)"))
		case ir.TermOccurs:
			e.line("return %s", e.fromValue(res, "rt.Occurs("+args[0]+", "+args[1]+")"))
		case ir.TermMatch:
			e.line("return %s", e.unbox(res, "rt.SyntacticMatch("+strings.Join(args, ", ")+")"))
		case ir.TermUnify:
			e.line("return %s", e.unbox(res, "rt.SyntacticUnify("+strings.Join(args, ", ")+")"))
		case ir.IOWrite:
			e.line("return %s", e.unbox(res, "rt.WriteTerm("+args[0]+", "+args[1]+")"))
		case ir.IORead:
			// a term of the result's sort (REM: of the sort of the
			// second argument's operator, the same)
			e.line("return %s", e.unbox(res, fmt.Sprintf("rt.ReadTerm(%s, %d)", args[0], e.ir.Sorts[res].Index)))
		case ir.ArrayNew:
			e.line("return %s", e.unbox(res, "rt.NewArray("+args[0]+", "+args[1]+")"))
		case ir.ArrayGet:
			e.line("return %s", e.unbox(res, "rt.ArrayGet("+args[0]+", "+args[1]+")"))
		case ir.ArraySet:
			e.line("return %s", e.unbox(res, "rt.ArraySet("+strings.Join(args, ", ")+")"))
		case ir.ArrayLength:
			e.line("return %s", e.fromValue(res, "rt.ArrayLength("+args[0]+")"))
		case ir.TermHash:
			e.line("return %s", e.fromValue(res, "rt.HashTerm("+args[0]+")"))
		}
		return
	}
	if !b.NeedsValues() {
		isTrue := func(i int) string {
			if _, ok := e.ir.Native(op.Args[i]); ok {
				return fmt.Sprintf("a%d", i)
			}
			return fmt.Sprintf("a%d == rt.True", i)
		}
		var v string
		switch b {
		case ir.TermEq:
			v = e.eqExpr(op.Args[0], "a0", "a1")
		case ir.TermNeq:
			v = "!(" + e.eqExpr(op.Args[0], "a0", "a1") + ")"
		case ir.BoolAnd:
			v = isTrue(0) + " && " + isTrue(1)
		case ir.BoolOr:
			v = isTrue(0) + " || " + isTrue(1)
		case ir.BoolNot:
			v = "!(" + isTrue(0) + ")"
		}
		e.line("return %s", e.fromValue(res, v))
		return
	}
	// the values of the arguments: vi, or ai when native
	vals := make([]string, len(op.Args))
	var oks []string
	for i, s := range op.Args {
		f := e.ir.FamilyOf(s)
		if !f.Boxed() {
			vals[i] = fmt.Sprintf("a%d", i)
			continue
		}
		vals[i] = fmt.Sprintf("v%d", i)
		a := fmt.Sprintf("a%d", i)
		if op.Total {
			// a boxed family whose terms of this sort are values: checked
			// (a stuck term would be a bug, a panic naming the operator)
			e.line("v%d := %s", i, e.unboxValue(f.Kind, a, op.Fun))
			continue
		}
		get := map[ir.BuiltinKind]string{ir.KindInt: "rt.IntOf", ir.KindBool: "rt.BoolOf", ir.KindStr: "rt.StrValue", ir.KindIdent: "rt.IdentOf"}[f.Kind]
		e.line("v%d, ok%d := %s(%s)", i, i, get, a)
		oks = append(oks, fmt.Sprintf("!ok%d", i))
	}
	if len(oks) > 0 {
		e.open("if %s {", strings.Join(oks, " || "))
		e.line("return %s // a stuck argument", e.stuck(o))
		e.close("}")
	}
	v := vals
	var value string
	switch b {
	case ir.IntAdd:
		value = v[0] + " + " + v[1]
	case ir.IntSub:
		value = v[0] + " - " + v[1]
	case ir.IntMul:
		value = v[0] + " * " + v[1]
	case ir.IntDiv:
		value = "rt.Div(" + v[0] + ", " + v[1] + ")"
	case ir.IntRem:
		value = "rt.Mod(" + v[0] + ", " + v[1] + ")"
	case ir.IntAnd:
		value = v[0] + " & " + v[1]
	case ir.IntOr:
		value = v[0] + " | " + v[1]
	case ir.IntNeg:
		value = "-" + v[0]
	case ir.CmpEq, ir.CmpNe, ir.CmpLt, ir.CmpLe, ir.CmpGt, ir.CmpGe:
		cmp := map[ir.BuiltinOp]string{ir.CmpEq: "==", ir.CmpNe: "!=", ir.CmpLt: "<", ir.CmpLe: "<=", ir.CmpGt: ">", ir.CmpGe: ">="}[b]
		x, y := v[0], v[1]
		if e.ir.FamilyOf(op.Args[0]).Kind == ir.KindBool && b != ir.CmpEq && b != ir.CmpNe {
			x, y = "b2i("+x+")", "b2i("+y+")"
			e.b2i = true
		}
		value = x + " " + cmp + " " + y
	case ir.StrLen:
		value = "rt.StrLen(" + v[0] + ")"
	case ir.StrCat:
		value = "rt.StrCat(" + v[0] + ", " + v[1] + ")"
	case ir.StrSpn:
		value = "rt.StrSpn(" + v[0] + ", " + v[1] + ")"
	case ir.StrCmp:
		value = "rt.StrCmp(" + v[0] + ", " + v[1] + ")"
	case ir.StrOfChar:
		value = "rt.StrOfChar(" + v[0] + ")"
	case ir.BoolToInt:
		value = "b2i(" + v[0] + ")"
		e.b2i = true
	case ir.IntToBool:
		value = v[0] + " != 0"
	case ir.IdentEq:
		value = v[0] + " == " + v[1]
	case ir.IdentNe:
		value = v[0] + " != " + v[1]
	case ir.IdentToString:
		value = "rt.IdentString(" + v[0] + ")"
	case ir.IOGetc:
		value = "rt.Getc(" + v[0] + ")"
	case ir.IOPutc:
		value = "rt.Putc(" + v[0] + ", " + v[1] + ")"
	case ir.IOOpen:
		value = "rt.Open(" + v[0] + ", " + v[1] + ")"
	case ir.IOClose:
		value = "rt.Close(" + v[0] + ")"
	case ir.IOFlush:
		value = "rt.Flush(" + v[0] + ")"
	case ir.IOPid:
		value = v[0]
	case ir.StrIndex:
		value = "rt.StrIndex(" + v[0] + ", " + v[1] + ")"
	case ir.StrModif:
		value = "rt.StrModif(" + v[0] + ", " + v[1] + ", " + v[2] + ")"
	case ir.StrSubstr:
		value = "rt.StrSubstr(" + v[0] + ", " + v[1] + ", " + v[2] + ")"
	}
	if b.Partial() {
		e.open("if r, ok := %s; ok {", value)
		e.line("return %s", e.fromValue(res, "r"))
		e.close("}")
		e.line("return %s // undefined on these values", e.stuck(o))
		return
	}
	e.line("return %s", e.fromValue(res, value))
}

// unboxValue is the value of kind k of the boxed value t received by the
// function fun (checked: rt.MustInt...).
func (e *emitter) unboxValue(k ir.BuiltinKind, t, fun string) string {
	get := map[ir.BuiltinKind]string{ir.KindInt: "rt.MustInt", ir.KindBool: "rt.MustBool", ir.KindStr: "rt.MustStr", ir.KindIdent: "rt.MustIdent"}[k]
	return fmt.Sprintf("%s(%s, %s)", get, t, goString(fun))
}

