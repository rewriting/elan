// Decision trees and rules

// occName is the name of the variable holding the term at a position.
func occName(o ir.Occ) string {
	var b strings.Builder
	fmt.Fprintf(&b, "a%d", o[0])
	for _, i := range o[1:] {
		fmt.Fprintf(&b, "_%d", i)
	}
	return b.String()
}

// usedVars are the variables of a rule used by its conditions or its
// right-hand side (the others are not bound: Go refuses unused variables).
func usedVars(r *ir.Rule) map[ir.VarID]bool {
	used := map[ir.VarID]bool{}
	var walk func(x *ir.Expr)
	walk = func(x *ir.Expr) {
		if x.Kind == ir.ExprVar {
			used[x.Var] = true
		}
		for i := range x.Args {
			walk(&x.Args[i])
		}
	}
	for _, c := range r.Conds {
		if c.Kind == ir.CondSame {
			used[c.A], used[c.B] = true, true
		} else if c.Kind == ir.CondAC || c.Kind == ir.CondEker {
			used[c.A] = true
		} else {
			walk(&c.Expr)
		}
	}
	walk(&r.Rhs)
	return used
}

// usedOccs are the positions read by the code of d; all: every rule is
// tried, whether it applies or not (a label).
func usedOccs(d *ir.Decision, rules []ir.Rule, into map[string]bool, all bool) {
	switch d.Kind {
	case ir.Try:
		used := usedVars(&rules[d.Rule])
		for _, b := range d.Bindings {
			if used[b.Var] {
				into[occName(b.Occ)] = true
			}
		}
		if all || !rules[d.Rule].Unconditional() {
			usedOccs(d.Next, rules, into, all)
		}
	case ir.Switch:
		into[occName(d.Occ)] = true
		for _, c := range d.Cases {
			usedOccs(c.Then, rules, into, all)
		}
		if d.Default != nil {
			usedOccs(d.Default, rules, into, all)
		}
	}
}

// decision writes the code of d; it tells whether the end of that code can
// be reached (it does not always return; a "terminating statement" in Go's
// terms): the code after it is emitted only then (go vet refuses
// unreachable code, Go a function without a final return).
func (e *emitter) decision(d *ir.Decision, rules []ir.Rule) bool {
	switch d.Kind {
	case ir.Try:
		if !e.tryRule(d, rules) {
			// the rule always applies: the next ones are never tried
			return false
		}
		return e.decision(d.Next, rules)
	case ir.Switch:
		if e.ir.FamilyOf(d.Sort) == nil {
			return e.symSwitch(d, rules)
		}
		return e.familySwitch(d, rules)
	}
	return true
}

// children binds the children of the head op at position occ (a term)
// that the code of then reads.
func (e *emitter) children(occ ir.Occ, o ir.OpID, then *ir.Decision, rules []ir.Rule) {
	used := map[string]bool{}
	usedOccs(then, rules, used, e.labelMode)
	name := occName(occ)
	for i, s := range e.ir.Ops[o].Args {
		c := occName(append(slices.Clone(occ), i))
		if used[c] {
			e.line("%s := %s", c, e.unbox(s, fmt.Sprintf("%s.Args[%d]", name, i)))
		}
	}
}

// symSwitch is a switch on the head symbol of a term of a sort of terms
// (see decision for the result).
func (e *emitter) symSwitch(d *ir.Decision, rules []ir.Rule) bool {
	name := occName(d.Occ)
	e.line("switch %s.Sym {", name)
	falls := false
	for _, c := range d.Cases {
		op := &e.ir.Ops[c.Head.Op]
		e.line("case %s:", symName(op))
		e.indent++
		e.children(d.Occ, c.Head.Op, c.Then, rules)
		falls = e.decision(c.Then, rules) || falls
		e.indent--
	}
	if d.Default != nil && d.Default.Kind != ir.Fail {
		e.line("default:")
		e.indent++
		falls = e.decision(d.Default, rules) || falls
		e.indent--
	} else {
		// no default: the other symbols go on after the switch
		falls = true
	}
	e.line("}")
	return falls
}

// familySwitch is a chain of tests on a value or term of a builtin family
// (see decision for the result).
func (e *emitter) familySwitch(d *ir.Decision, rules []ir.Rule) bool {
	name := occName(d.Occ)
	started, closed, falls := false, false, false
	for _, c := range d.Cases {
		test := e.headTest(d.Sort, name, c.Head)
		switch {
		case test == "" && !started:
			e.open("{")
		case test == "":
			e.indent--
			e.open("} else {")
		case !started:
			e.open("if %s {", test)
		default:
			e.indent--
			e.open("} else if %s {", test)
		}
		started = true
		if c.Head.Kind == ir.HeadOp {
			op := &e.ir.Ops[c.Head.Op]
			if op.Kind == ir.Injection {
				child := occName(append(slices.Clone(d.Occ), 0))
				used := map[string]bool{}
				usedOccs(c.Then, rules, used, e.labelMode)
				if used[child] {
					e.line("%s := %s", child, name)
				}
			} else if op.Kind != ir.BoolConst {
				e.children(d.Occ, c.Head.Op, c.Then, rules)
			}
		}
		falls = e.decision(c.Then, rules) || falls
		if test == "" {
			// the other cases and the default are never reached
			e.close("}")
			closed = true
			break
		}
	}
	if closed {
		// a block or a chain ending with an else
		return falls
	}
	if d.Default != nil && d.Default.Kind != ir.Fail {
		if started {
			e.indent--
			e.open("} else {")
		} else {
			e.open("{")
		}
		falls = e.decision(d.Default, rules) || falls
		e.close("}")
		return falls
	} else if started {
		e.close("}")
	}
	// no else: the other values go on after the tests
	return true
}

// tryRule applies a rule whose left-hand side matches, if its conditions
// hold: a block of nested ifs ending with the return of its right-hand
// side (normalisation) or its result passed to k (a label, which then
// goes on with the next rules; with first, it stops after the first rule
// that has a result). It tells whether the code after it is reached (see
// decision).
func (e *emitter) tryRule(d *ir.Decision, rules []ir.Rule) bool {
	r := &rules[d.Rule]
	used := usedVars(r)
	e.line("// %s", comment(r.Text))
	block := e.labelMode || !r.Unconditional()
	if block {
		// a block: the variables of the rule are local to it
		e.open("{")
	}
	for _, b := range d.Bindings {
		if used[b.Var] {
			e.line("%s := %s", r.Vars[b.Var].Name, occName(b.Occ))
		}
	}
	falls := e.conds(r, 0, used, 0)
	if block {
		e.close("}")
	}
	if e.labelMode {
		e.open("if first && found {")
		e.line("return false // dc: the results of the first rule that has one")
		e.close("}")
		return true
	}
	return falls
}

// conds writes the conditions of rule r from the i-th on, then its
// application; depth is the number of enclosing continuations (closures
// of `where p := (S) t`), where a failing condition returns false (S then
// gives its next result). It tells whether the code after it is reached:
// a condition that may fail opens an if, after which the code goes on.
func (e *emitter) conds(r *ir.Rule, from int, used map[ir.VarID]bool, depth int) bool {
	opens := 0
	defer func() {
		for range opens {
			e.close("}")
		}
	}()
	for j := from; j < len(r.Conds); j++ {
		c := r.Conds[j]
		switch c.Kind {
		case ir.CondSame, ir.CondIf, ir.CondLet:
			opens += e.simpleCond(&c, r, used)
		case ir.CondMatch:
			s := e.ir.ExprSort(&c.Expr, r.Vars)
			if c.Pat.Kind == ir.PatVar {
				if used[c.Pat.Var] {
					e.line("%s := %s", r.Vars[c.Pat.Var].Name, e.typedExpr(&c.Expr, r.Vars))
				} else {
					e.line("_ = %s", e.expr(&c.Expr, r.Vars))
				}
				continue
			}
			m := fmt.Sprintf("m%d", e.next())
			e.line("%s := %s", m, e.typedExpr(&c.Expr, r.Vars))
			n, read := e.patternCheck(&c.Pat, m, s, r, used)
			opens += n
			if !read {
				e.line("_ = %s // the pattern reads nothing of it", m)
			}
		case ir.CondApply:
			// (its code ends with an if)
			e.apply(r, j, used, depth)
			return true
		case ir.CondAC:
			// (its code ends with an if or a loop)
			e.acMatch(r, j, used, depth)
			return true
		case ir.CondEker:
			// (its code ends with a loop)
			e.ekerMatch(r, j, used, depth)
			return true
		}
	}
	rhs := ""
	if e.late != nil {
		rhs = e.lateBind(r, used)
		opens++
	}
	e.line("rt.Step()")
	if rhs == "" {
		rhs = e.expr(&r.Rhs, r.Vars)
	}
	if e.ext != nil {
		// modulo an extension: op(E, rhs), the arguments of rhs merged
		// with E when op is at its top
		op := &e.ir.Ops[e.ext.op]
		args := []string{rhs}
		if r.Rhs.Kind == ir.ExprOp && r.Rhs.Op == e.ext.op {
			args = e.acArgs(&r.Rhs, r.Vars)
		}
		rhs = fmt.Sprintf("rt.ExtendAC(%s, %s, %s, %s)", symName(op), acFun(op), e.ext.rest, strings.Join(args, ", "))
	}
	switch {
	case e.labelMode && depth == 0:
		e.line("found = true")
		e.open("if k(%s) {", rhs)
		e.line("return true")
		e.close("}")
		return true
	case e.labelMode:
		e.line("found = true")
		e.line("return k(%s)", rhs)
	case depth == 0:
		e.ret(rhs)
	default:
		e.line("%s, %s = %s, true", e.res, e.ok, rhs)
		e.line("return true")
	}
	return opens > 0
}

// simpleCond writes a condition that gives at most one solution and binds
// no pattern variable (CondSame, CondIf, CondLet); it returns the number of
// ifs it opens.
func (e *emitter) simpleCond(c *ir.Cond, r *ir.Rule, used map[ir.VarID]bool) int {
	switch c.Kind {
	case ir.CondSame:
		e.open("if %s {", e.eqExpr(r.Vars[c.A].Sort, r.Vars[c.A].Name, r.Vars[c.B].Name))
		return 1
	case ir.CondIf:
		x := e.expr(&c.Expr, r.Vars)
		if _, ok := e.ir.Native(e.ir.ExprSort(&c.Expr, r.Vars)); !ok {
			x += " == rt.True"
		}
		e.open("if %s {", x)
		return 1
	case ir.CondLet:
		if used[c.A] {
			e.line("%s := %s", r.Vars[c.A].Name, e.typedExpr(&c.Expr, r.Vars))
		} else {
			e.line("_ = %s", e.expr(&c.Expr, r.Vars))
		}
		return 0
	}
	panic("not a simple condition")
}

// apply writes the condition j of r, `where p := (S) t`, and the rest of
// the rule in the continuation of S: each result of S matched against p,
// the conditions after it checked (a failure returns false: S gives its
// next result). A normalisation function keeps the first result for which
// the rule applies (res, ok); a label passes every one to k.
func (e *emitter) apply(r *ir.Rule, j int, used map[ir.VarID]bool, depth int) {
	c := &r.Conds[j]
	st := &e.ir.Strategies[c.Strategy]
	ty := e.goType(st.Sort)
	n := e.next()
	m, y := fmt.Sprintf("m%d", n), fmt.Sprintf("y%d", n)
	e.line("%s := %s", m, e.typedExpr(&c.Expr, r.Vars))
	e.line("// each result of %s (the conditions after it backtrack)", comment(st.Name))
	keepFirst := !e.labelMode && depth == 0
	if keepFirst {
		e.res, e.ok = fmt.Sprintf("res%d", n), fmt.Sprintf("ok%d", n)
		e.line("var %s %s", e.res, e.resType)
		e.line("%s := false", e.ok)
		e.open("%s(%s, func(%s %s) bool {", st.Fun, m, y, ty)
	} else {
		e.open("if %s(%s, func(%s %s) bool {", st.Fun, m, y, ty)
	}
	opens, _ := e.patternCheck(&c.Pat, y, st.Sort, r, used)
	falls := e.conds(r, j+1, used, depth+1)
	for range opens {
		e.close("}")
	}
	if falls || opens > 0 {
		e.line("return false")
	}
	if keepFirst {
		e.close("})")
		e.open("if %s {", e.ok)
		e.ret(e.res)
		e.close("}")
	} else {
		e.indent--
		e.open("}) {")
		e.line("return true")
		e.close("}")
	}
}

// patternCheck matches the term or value t of sort s against p, binding
// its variables; it opens an if per test and returns their number, and
// whether its code reads t. A pattern can read nothing of t (Go refuses a
// variable declared and not used, the caller then discards t): a variable
// the rule does not use, an injection into a sort whose values are all
// injected (no test) above such a pattern, or an operator that is never a
// normal form (a test `if false`).
func (e *emitter) patternCheck(p *ir.Pattern, t string, s ir.SortID, r *ir.Rule, used map[ir.VarID]bool) (int, bool) {
	switch p.Kind {
	case ir.PatVar:
		if used[p.Var] {
			e.line("%s := %s", r.Vars[p.Var].Name, t)
			return 0, true
		}
		return 0, false
	case ir.PatInt:
		e.open("if %s {", e.headTest(s, t, ir.Head{Kind: ir.HeadInt, Int: p.Int}))
		return 1, true
	case ir.PatStr:
		e.open("if %s {", e.headTest(s, t, ir.Head{Kind: ir.HeadStr, Str: p.Str}))
		return 1, true
	}
	op := &e.ir.Ops[p.Op]
	switch {
	case op.Kind == ir.BoolConst:
		e.open("if %s {", e.headTest(s, t, ir.Head{Kind: ir.HeadOp, Op: p.Op}))
		return 1, true
	case op.Kind == ir.Injection:
		n, read := 0, false
		if test := e.headTest(s, t, ir.Head{Kind: ir.HeadOp, Op: p.Op}); test != "" {
			e.open("if %s {", test)
			n, read = 1, true
		}
		m, sub := e.patternCheck(&p.Args[0], t, op.Args[0], r, used)
		return n + m, read || sub
	case !op.Variant:
		e.open("if false { // %s is never a normal form", comment(op.Decl))
		return 1, false
	}
	e.open("if %s.Sym == %s {", t, symName(op))
	n := 1
	for i := range p.Args {
		a := &p.Args[i]
		c := e.unbox(op.Args[i], fmt.Sprintf("%s.Args[%d]", t, i))
		if a.Kind == ir.PatVar {
			if used[a.Var] {
				e.line("%s := %s", r.Vars[a.Var].Name, c)
			}
			continue
		}
		v := fmt.Sprintf("p%d", e.next())
		e.line("%s := %s", v, c)
		m, read := e.patternCheck(a, v, op.Args[i], r, used)
		n += m
		if !read {
			e.line("_ = %s // the pattern reads nothing of it", v)
		}
	}
	return n, true
}

func (e *emitter) mainFunc() {
	p := e.ir
	e.line("// ==== main ====")
	e.line("")
	if p.Start.Strategy < 0 {
		e.line("// main runs the start term of the query (-noInput), normalised and printed.")
	} else {
		e.line("// main runs the start term of the query (-noInput), normalised, then each")
		e.line("// result of the start strategy printed.")
	}
	e.open("func main() {")
	e.open("rt.Main(%s, func(s *rt.Session) {", goString(p.Start.QuerySort))
	result := "Result"
	if k, ok := p.Native(p.Start.Sort); ok {
		result = map[ir.BuiltinKind]string{ir.KindInt: "ResultInt", ir.KindBool: "ResultBool", ir.KindStr: "ResultStr"}[k]
	}
	if p.Start.Strategy < 0 {
		e.line("s.%s(%s)", result, e.expr(&p.Start.Term, nil))
	} else {
		st := &p.Strategies[p.Start.Strategy]
		e.line("t := %s", e.typedExpr(&p.Start.Term, nil))
		e.line("// each result of %s", comment(st.Name))
		e.open("%s(t, func(r %s) bool {", st.Fun, e.goType(st.Sort))
		e.line("s.%s(r)", result)
		e.line("return false")
		e.close("})")
	}
	e.close("})")
	e.close("}")
}
