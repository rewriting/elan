// Types and values

func goNative(k ir.BuiltinKind) string {
	switch k {
	case ir.KindInt, ir.KindIdent:
		return "int32"
	case ir.KindBool:
		return "bool"
	}
	return "string"
}

// goType is the Go type of the terms of sort s.
func (e *emitter) goType(s ir.SortID) string {
	if k, ok := e.ir.Native(s); ok {
		return goNative(k)
	}
	return "rt.Term"
}

// asTerm is the term of x, the representation of a term of sort s (to be
// stored in a node): a native value is boxed.
func (e *emitter) asTerm(s ir.SortID, x string) string {
	k, ok := e.ir.Native(s)
	if !ok {
		return x
	}
	return boxValue(k, x)
}

// fromValue is the representation in sort s of the native value v of the
// family of s: v itself, or its box when the family is boxed.
func (e *emitter) fromValue(s ir.SortID, v string) string {
	if _, ok := e.ir.Native(s); ok {
		return v
	}
	return boxValue(e.ir.FamilyOf(s).Kind, v)
}

func boxValue(k ir.BuiltinKind, v string) string {
	switch k {
	case ir.KindInt:
		return "rt.MkInt(" + v + ")"
	case ir.KindBool:
		return "rt.MkBool(" + v + ")"
	case ir.KindIdent:
		return "rt.MkIdent(" + v + ")"
	}
	return "rt.MkStr(" + v + ")"
}

// unbox is the value of sort s held by the term t (a child of a node).
func (e *emitter) unbox(s ir.SortID, t string) string {
	k, ok := e.ir.Native(s)
	if !ok {
		return t
	}
	switch k {
	case ir.KindInt, ir.KindIdent:
		return t + ".Int"
	case ir.KindBool:
		return t + " == rt.True"
	}
	return "rt.StrOf(" + t + ")"
}

func symName(op *ir.Op) string { return "sym_" + op.Fun }

// eqExpr is the test that a and b, of sort s, are the same term: rt.Eq
// on terms (int nodes are not shared), == on native values.
func (e *emitter) eqExpr(s ir.SortID, a, b string) string {
	if _, ok := e.ir.Native(s); ok {
		return a + " == " + b
	}
	if strings.HasPrefix(e.ir.Sorts[s].Name, "builtinArray[") {
		// arrays: by contents (S7e task 7)
		return "rt.ArrayEq(" + a + ", " + b + ")"
	}
	return "rt.Eq(" + a + ", " + b + ")"
}

// acFun is the normalisation function of the AC operator op over a
// multiset; nil for a constructor (rt.ApplyAC and rt.ExtendAC then
// build the term).
func acFun(op *ir.Op) string {
	if op.Kind != ir.Defined {
		return "nil"
	}
	return op.ACFun
}

// mk is the construction of the term o(args), args being terms.
func (e *emitter) mk(o ir.OpID, args []string) string {
	sym := symName(&e.ir.Ops[o])
	if e.ir.Ops[o].AC {
		// flattened and sorted
		return "rt.MkAC2(" + sym + ", " + strings.Join(args, ", ") + ")"
	}
	switch len(args) {
	case 0:
		return "rt.Mk0(" + sym + ")"
	case 1, 2, 3:
		return fmt.Sprintf("rt.Mk%d(%s, %s)", len(args), sym, strings.Join(args, ", "))
	}
	return "rt.Mk(" + sym + ", " + strings.Join(args, ", ") + ")"
}

// stuck is the term o(a0, ...) of the function's arguments.
func (e *emitter) stuck(o ir.OpID) string {
	op := &e.ir.Ops[o]
	var args []string
	for i, s := range op.Args {
		args = append(args, e.asTerm(s, fmt.Sprintf("a%d", i)))
	}
	return e.mk(o, args)
}

func goInt(n int32) string { return strconv.FormatInt(int64(n), 10) }

// goString is a Go literal of a byte string (bytes above 127 escaped).
func goString(s string) string { return strconv.Quote(s) }

// expr is an expression computing the normal form of x.
func (e *emitter) expr(x *ir.Expr, vars []ir.Var) string {
	switch x.Kind {
	case ir.ExprVar:
		return vars[x.Var].Name
	case ir.ExprInt:
		return e.fromValue(e.ir.ExprSort(x, vars), goInt(x.Int))
	case ir.ExprStr:
		return e.fromValue(e.ir.ExprSort(x, vars), goString(x.Str))
	case ir.ExprIdent:
		// an identifier: its index
		return e.fromValue(e.ir.ExprSort(x, vars), goInt(x.Int))
	}
	op := &e.ir.Ops[x.Op]
	switch op.Kind {
	case ir.Injection:
		return e.expr(&x.Args[0], vars)
	case ir.BoolConst:
		if _, ok := e.ir.Native(op.Result); ok {
			return strconv.FormatBool(op.Bool)
		}
		if op.Bool {
			return "rt.True"
		}
		return "rt.False"
	}
	if op.AC {
		if args := e.acArgs(x, vars); len(args) > 2 {
			// one AC term: normalised once, as a whole
			return fmt.Sprintf("rt.ApplyAC(%s, %s, %s)", symName(op), acFun(op), strings.Join(args, ", "))
		}
	}
	var args []string
	for i := range x.Args {
		args = append(args, e.expr(&x.Args[i], vars))
	}
	return op.Fun + "(" + strings.Join(args, ", ") + ")"
}

// acArgs are the expressions of the arguments of the AC operator at the
// top of x, the nested applications of the same operator flattened: the
// interpreter flattens an AC term before normalising it (its subterms of
// the same operator are not redexes of their own: F(a, F(b, c)) is
// normalised as the multiset a, b, c, as REM does).
func (e *emitter) acArgs(x *ir.Expr, vars []ir.Var) []string {
	var args []string
	for i := range x.Args {
		a := &x.Args[i]
		if a.Kind == ir.ExprOp && a.Op == x.Op {
			args = append(args, e.acArgs(a, vars)...)
		} else {
			args = append(args, e.expr(a, vars))
		}
	}
	return args
}

// typedExpr is expr, an int literal typed int32 (for `x := ...`).
func (e *emitter) typedExpr(x *ir.Expr, vars []ir.Var) string {
	s := e.expr(x, vars)
	if _, err := strconv.Atoi(s); err == nil {
		return "int32(" + s + ")"
	}
	return s
}

// headTest is the test that the term or value t of sort s has head h; ""
// when it always has (an injection into a native family).
func (e *emitter) headTest(s ir.SortID, t string, h ir.Head) string {
	_, native := e.ir.Native(s)
	switch h.Kind {
	case ir.HeadInt:
		if native {
			return t + " == " + goInt(h.Int)
		}
		return "rt.IsInt(" + t + ") && " + t + ".Int == " + goInt(h.Int)
	case ir.HeadStr:
		if native {
			return t + " == " + goString(h.Str)
		}
		return "rt.IsStr(" + t + ") && rt.StrOf(" + t + ") == " + goString(h.Str)
	case ir.HeadIdent:
		// (identifiers by index)
		if native {
			return t + " == " + goInt(h.Int)
		}
		return "rt.IsIdent(" + t + ") && " + t + ".Int == " + goInt(h.Int)
	}
	op := &e.ir.Ops[h.Op]
	switch op.Kind {
	case ir.BoolConst:
		switch {
		case native && op.Bool:
			return t
		case native:
			return "!" + t
		case op.Bool:
			return t + " == rt.True"
		}
		return t + " == rt.False"
	case ir.Injection:
		if native {
			return ""
		}
		if len(e.otherStuck(h.Op)) == 0 {
			return ""
		}
		if !slices.Contains(e.injTests, h.Op) {
			e.injTests = append(e.injTests, h.Op)
		}
		return "is_" + op.Fun + "(" + t + ")"
	}
	return t + ".Sym == " + symName(op)
}

// otherStuck are the operators whose stuck terms are terms of the sort of
// the injection inj, but not injections (their sort is not the builtin
// sort).
func (e *emitter) otherStuck(inj ir.OpID) []ir.OpID {
	op := &e.ir.Ops[inj]
	var v []ir.OpID
	for _, o := range e.ir.FamilyOf(op.Result).Stuck {
		if e.ir.Ops[o].Result != op.Args[0] {
			v = append(v, o)
		}
	}
	return v
}

// injTest writes the test of a pattern inj(x) on the boxed terms of the
// sort of the injection inj: a term of that sort is a value, a stuck term
// of the builtin sort (both the injection of a builtin term) or a stuck
// term of the sort itself (not an injection).
func (e *emitter) injTest(inj ir.OpID) {
	op := &e.ir.Ops[inj]
	var syms []string
	for _, o := range e.otherStuck(inj) {
		syms = append(syms, symName(&e.ir.Ops[o]))
	}
	e.line("// is_%s tells whether t, of sort %s, is the injection %s of a term", op.Fun,
		comment(e.ir.Sorts[op.Result].Name), op.Fun)
	e.line("// of sort %s (a value or a stuck term of that sort).", comment(e.ir.Sorts[op.Args[0]].Name))
	e.open("func is_%s(t rt.Term) bool {", op.Fun)
	e.line("switch t.Sym {")
	e.line("case %s:", strings.Join(syms, ", "))
	e.line("\treturn false")
	e.line("}")
	e.line("return true")
	e.close("}")
	e.line("")
}

