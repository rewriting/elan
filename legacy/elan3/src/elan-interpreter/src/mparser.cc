static void errcommon(lstream &f)
{ lexem s;
  /* int n; */
  f.ilex(s);
  sterr << "\ton symbol \'" << s.alfsy() << "\'" /* <<" in state " << st */;
  f.beforemess(s);
}


static void syerror(lstream &f,int st)
{ int n;
  lexem s;
  struct spr *p;
  f.oerr();
  sterr << "[PARSER] syntax error ";
  errcommon(f);
  sterr << "\tone of (";
  p=STTAB[st].pr; n=STTAB[st].npr;
  while (n--) {
    s.maccsymtolex((p++)->sym);
    sterr << " \'" << s.alfsy() << "\' ";
  }
  sterr << ") expected \n";
}

